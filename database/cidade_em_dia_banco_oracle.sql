-- 1. TABELAS PRINCIPAIS E TABELAS DE APOIO

CREATE TABLE USUARIO (
    ID_USUARIO          NUMBER(6)       NOT NULL,
    NOME_USUARIO        VARCHAR2(200)   NOT NULL,
    EMAIL_USUARIO       VARCHAR2(200)   NOT NULL,
    SENHA_USUARIO       VARCHAR2(255)   NOT NULL,
    TELEFONE_USUARIO    VARCHAR2(20)    NOT NULL,
    TIPO_USUARIO        VARCHAR2(20)    DEFAULT 'CIDADAO' NOT NULL,
    DT_CADASTRO_USUARIO DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL_USUARIO),
    CONSTRAINT CK_USUARIO_TIPO CHECK (TIPO_USUARIO IN ('CIDADAO', 'ADMIN'))
);

CREATE TABLE BAIRRO (
    ID_BAIRRO       NUMBER(6)       NOT NULL,
    NOME_BAIRRO     VARCHAR2(100)   NOT NULL,
    CIDADE_BAIRRO   VARCHAR2(100)   NOT NULL,
    ESTADO_BAIRRO   VARCHAR2(2)     NOT NULL,
    CONSTRAINT PK_BAIRRO PRIMARY KEY (ID_BAIRRO)
);

CREATE TABLE CATEGORIA (
    ID_CATEGORIA           NUMBER(6)       NOT NULL,
    NOME_CATEGORIA         VARCHAR2(50)    NOT NULL,
    DESCRICAO_CATEGORIA    VARCHAR2(200),
    CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UK_CATEGORIA_NOME UNIQUE (NOME_CATEGORIA)
);

CREATE TABLE PRIORIDADE (
    ID_PRIORIDADE          NUMBER(6)       NOT NULL,
    NOME_PRIORIDADE        VARCHAR2(20)    NOT NULL,
    DESCRICAO_PRIORIDADE   VARCHAR2(200),
    CONSTRAINT PK_PRIORIDADE PRIMARY KEY (ID_PRIORIDADE),
    CONSTRAINT UK_PRIORIDADE_NOME UNIQUE (NOME_PRIORIDADE)
);

CREATE TABLE STATUS (
    ID_STATUS          NUMBER(6)       NOT NULL,
    NOME_STATUS        VARCHAR2(30)    NOT NULL,
    DESCRICAO_STATUS   VARCHAR2(200),
    CONSTRAINT PK_STATUS PRIMARY KEY (ID_STATUS),
    CONSTRAINT UK_STATUS_NOME UNIQUE (NOME_STATUS)
);

CREATE TABLE OCORRENCIA (
    ID_OCORRENCIA              NUMBER(6)       NOT NULL,
    USUARIO_ID_USUARIO         NUMBER(6)       NOT NULL,
    BAIRRO_ID_BAIRRO           NUMBER(6)       NOT NULL,
    CATEGORIA_ID_CATEGORIA     NUMBER(6)       NOT NULL,
    PRIORIDADE_ID_PRIORIDADE   NUMBER(6)       NOT NULL,
    STATUS_ID_STATUS           NUMBER(6)       NOT NULL,
    TITULO_OCORRENCIA          VARCHAR2(100)   NOT NULL,
    DESCRICAO_OCORRENCIA       VARCHAR2(500)   NOT NULL,
    FOTO_OCORRENCIA            VARCHAR2(500),
    DT_REGISTRO_OCORRENCIA     DATE            DEFAULT SYSDATE NOT NULL,
    ENDERECO_OCORRENCIA        VARCHAR2(200)   NOT NULL,
    LATITUDE_OCORRENCIA        NUMBER(10,7),
    LONGITUDE_OCORRENCIA       NUMBER(10,7),
    CONSTRAINT PK_OCORRENCIA PRIMARY KEY (ID_OCORRENCIA),
    CONSTRAINT FK_USUARIO_OCORRENCIA FOREIGN KEY (USUARIO_ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_BAIRRO_OCORRENCIA FOREIGN KEY (BAIRRO_ID_BAIRRO)
        REFERENCES BAIRRO (ID_BAIRRO),
    CONSTRAINT FK_CATEGORIA_OCORRENCIA FOREIGN KEY (CATEGORIA_ID_CATEGORIA)
        REFERENCES CATEGORIA (ID_CATEGORIA),
    CONSTRAINT FK_PRIORIDADE_OCORRENCIA FOREIGN KEY (PRIORIDADE_ID_PRIORIDADE)
        REFERENCES PRIORIDADE (ID_PRIORIDADE),
    CONSTRAINT FK_STATUS_OCORRENCIA FOREIGN KEY (STATUS_ID_STATUS)
        REFERENCES STATUS (ID_STATUS),
    CONSTRAINT CK_OCORRENCIA_LATITUDE CHECK (
        LATITUDE_OCORRENCIA IS NULL OR LATITUDE_OCORRENCIA BETWEEN -90 AND 90
    ),
    CONSTRAINT CK_OCORRENCIA_LONGITUDE CHECK (
        LONGITUDE_OCORRENCIA IS NULL OR LONGITUDE_OCORRENCIA BETWEEN -180 AND 180
    )
);

CREATE TABLE HISTORICO_OCORRENCIA (
    ID_HISTORICO                 NUMBER(6)       NOT NULL,
    USUARIO_ID_USUARIO           NUMBER(6)       NOT NULL,
    STATUS_ID_STATUS             NUMBER(6)       NOT NULL,
    OCORRENCIA_ID_OCORRENCIA     NUMBER(6)       NOT NULL,
    DT_ALTERACAO_HISTORICO       DATE            DEFAULT SYSDATE NOT NULL,
    OBSERVACAO_HISTORICO         VARCHAR2(500)   NOT NULL,
    CONSTRAINT PK_HISTORICO_OCORRENCIA PRIMARY KEY (ID_HISTORICO),
    CONSTRAINT FK_USUARIO_HIST_OCORRENCIA FOREIGN KEY (USUARIO_ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_STATUS_HIST_OCORRENCIA FOREIGN KEY (STATUS_ID_STATUS)
        REFERENCES STATUS (ID_STATUS),
    CONSTRAINT FK_OCORRENCIA_HIST_OCORRENCIA FOREIGN KEY (OCORRENCIA_ID_OCORRENCIA)
        REFERENCES OCORRENCIA (ID_OCORRENCIA)
);

CREATE TABLE RELATO (
    ID_RELATO                    NUMBER(6)       NOT NULL,
    OCORRENCIA_ID_OCORRENCIA     NUMBER(6)       NOT NULL,
    USUARIO_ID_USUARIO           NUMBER(6)       NOT NULL,
    DT_REGISTRO_RELATO           DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_RELATO PRIMARY KEY (ID_RELATO),
    CONSTRAINT FK_OCORRENCIA_RELATO FOREIGN KEY (OCORRENCIA_ID_OCORRENCIA)
        REFERENCES OCORRENCIA (ID_OCORRENCIA),
    CONSTRAINT FK_USUARIO_RELATO FOREIGN KEY (USUARIO_ID_USUARIO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT UK_RELATO_USUARIO_OCORRENCIA
        UNIQUE (OCORRENCIA_ID_OCORRENCIA, USUARIO_ID_USUARIO)
);

